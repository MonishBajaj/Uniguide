"""Generate src/uniguide_worker/db_enums.py from the database's enum types.

The SQL migrations are the source of truth; TypeScript gets the same values from
`supabase gen types`. Run `pnpm db:types` after changing an enum.
"""

from __future__ import annotations

import os
import sys
from pathlib import Path

import psycopg

OUT = Path(__file__).resolve().parents[1] / "src" / "uniguide_worker" / "db_enums.py"
DEFAULT_URL = "postgresql://postgres:postgres@127.0.0.1:54322/postgres"


def class_name(enum_name: str) -> str:
    return "".join(part.capitalize() for part in enum_name.split("_"))


def member_name(value: str) -> str:
    name = value.upper()
    return f"V_{name}" if name[0].isdigit() else name


def render(enums: dict[str, list[str]]) -> str:
    lines = [
        '"""Generated by worker/scripts/gen_enums.py from the database. Do not edit."""',
        "",
        "from enum import StrEnum",
        "",
    ]
    for name, values in sorted(enums.items()):
        lines += ["", f"class {class_name(name)}(StrEnum):"]
        lines += [f'    {member_name(v)} = "{v}"' for v in values]
        lines.append("")
    return "\n".join(lines)


def main() -> None:
    url = os.environ.get("OPERATOR_DATABASE_URL", DEFAULT_URL)
    with psycopg.connect(url) as conn:
        rows = conn.execute(
            """
            select t.typname, e.enumlabel
            from pg_type t
            join pg_enum e on e.enumtypid = t.oid
            join pg_namespace n on n.oid = t.typnamespace
            where n.nspname = 'public'
            order by t.typname, e.enumsortorder
            """
        ).fetchall()
    enums: dict[str, list[str]] = {}
    for typname, label in rows:
        enums.setdefault(typname, []).append(label)
    content = render(enums)
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != content:
            sys.exit(f"{OUT} is out of date; run pnpm db:types")
        return
    OUT.write_text(content)


if __name__ == "__main__":
    main()
